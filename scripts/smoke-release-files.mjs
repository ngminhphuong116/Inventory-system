import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { listPackage, extractFile } from '@electron/asar';
import ExcelJS from 'exceljs';
const root = resolve(import.meta.dirname, '..');
const directory = join(root, 'tmp', 'Kiểm thử phát hành', 'Tệp xuất');
await mkdir(directory, { recursive: true });
const bundle = join(root, 'tmp', 'report-release.cjs');
await build({ entryPoints: [join(root, 'src/pages/ReportStock/report-excel.ts')], outfile: bundle, bundle: true, platform: 'node', format: 'cjs' });
const dataBundle = join(root, 'tmp', 'report-data-release.cjs');
await build({ entryPoints: [join(root, 'src/pages/ReportStock/report-data.ts')], outfile: dataBundle, bundle: true, platform: 'node', format: 'cjs', packages: 'external' });
const { buildFinancialReportWorkbook } = await import(pathToFileURL(bundle).href);
const { buildFinancialReport } = await import(pathToFileURL(dataBundle).href);
const startDate = new Date(2026, 9, 1);
const endDate = new Date(2026, 9, 31);
const report = buildFinancialReport({ imports: [], exports: [], sales: [], startTime: startDate.getTime(), endTime: endDate.getTime() });
const workbook = await buildFinancialReportWorkbook({ report, startDate, endDate });
const excelPath = join(directory, 'Báo cáo kiểm thử.xlsx');
await workbook.xlsx.writeFile(excelPath);
const { Workbook } = ExcelJS;
const reopened = new Workbook();
await reopened.xlsx.readFile(excelPath);
if (reopened.worksheets.length !== 4) throw new Error('Excel export roundtrip failed');
const jsonPath = join(directory, 'Tệp JSON kiểm thử.json');
await writeFile(jsonPath, JSON.stringify({ note: 'Dữ liệu tổng hợp kiểm thử đường dẫn, không phải backup doanh nghiệp' }), 'utf8');
if (!JSON.parse(await readFile(jsonPath, 'utf8')).note.includes('kiểm thử')) throw new Error('UTF-8 JSON roundtrip failed');
const { version } = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const asar = join(root, 'release', version, 'installers', 'win-unpacked', 'resources', 'app.asar');
const qaAsar = join(root, 'release', version, 'qa-installers', 'win-unpacked', 'resources', 'app.asar');
const files = listPackage(asar);
const forbidden = files.filter(name => /(?:node_modules|github-source|\.firebaserc|service.?account|\.env|(?:setup|uninstall).*\.exe|\.xlsx|\.git(?:[\\/]|$))/i.test(name));
if (forbidden.length) throw new Error(`Unexpected files in app.asar: ${forbidden.join(', ')}`);
const hash = path => readFile(path).then(bytes => createHash('sha256').update(bytes).digest('hex'));
const releaseHash = await hash(asar);
if (releaseHash !== await hash(qaAsar)) throw new Error('QA and release payloads differ');
const manifest = JSON.parse(extractFile(asar, 'package.json').toString('utf8'));
if (Object.keys(manifest.dependencies || {}).length) throw new Error('Unexpected runtime npm dependencies');
console.log(JSON.stringify({ excel: { sheets: reopened.worksheets.map(sheet => sheet.name), bytes: (await readFile(excelPath)).length }, jsonUtf8: true, asar: { entries: files.length, forbiddenFiles: forbidden, releaseAndQaIdentical: true, sha256: releaseHash } }, null, 2));
